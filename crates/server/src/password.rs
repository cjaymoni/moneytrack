//! Passwords.
//!
//! Argon2id with the crate's own defaults, which are the ones the RFC recommends and are
//! revisited by people who think about this more than we do. One place, so there is no
//! second call site with weaker parameters.

use argon2::Argon2;
use argon2::password_hash::phc::PasswordHash;
use argon2::password_hash::{PasswordHasher, PasswordVerifier};

use crate::error::ApiError;

/// The shortest password accepted.
///
/// Length and nothing else: no character-class rules, which push people towards
/// `Password1!` and are worse than the thing they replace.
pub const MIN_LENGTH: usize = 12;

/// The longest, so a megabyte of input cannot be used to tie up a core hashing it.
pub const MAX_LENGTH: usize = 256;

/// Hashes a password for storage.
///
/// # Errors
/// [`ApiError::Invalid`] if the password is too short or too long, or
/// [`ApiError::Internal`] if hashing fails.
pub fn hash(password: &str) -> Result<String, ApiError> {
    check_length(password)?;
    // The salt is generated by the hasher, from the OS, per call.
    Argon2::default()
        .hash_password(password.as_bytes())
        .map(|hash| hash.to_string())
        .map_err(|error| ApiError::Internal {
            operation: "hash a password",
            reason: error.to_string(),
        })
}

/// Checks a password against a stored hash.
///
/// A malformed stored hash is an internal error rather than a failed sign-in: it means a row
/// was written by something that is not this code, and quietly answering "wrong password"
/// would hide that for ever.
///
/// # Errors
/// [`ApiError::Internal`] if the stored hash will not parse.
pub fn verify(password: &str, stored: &str) -> Result<bool, ApiError> {
    let parsed = PasswordHash::new(stored).map_err(|error| ApiError::Internal {
        operation: "read a stored password hash",
        reason: error.to_string(),
    })?;
    Ok(Argon2::default()
        .verify_password(password.as_bytes(), &parsed)
        .is_ok())
}

/// Refuses a password by length alone.
fn check_length(password: &str) -> Result<(), ApiError> {
    let length = password.chars().count();
    if length < MIN_LENGTH {
        return Err(ApiError::Invalid {
            field: "password".to_owned(),
            reason: format!("it needs at least {MIN_LENGTH} characters"),
        });
    }
    if length > MAX_LENGTH {
        return Err(ApiError::Invalid {
            field: "password".to_owned(),
            reason: format!("it cannot be longer than {MAX_LENGTH} characters"),
        });
    }
    Ok(())
}
